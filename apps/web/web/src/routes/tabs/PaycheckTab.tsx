function DirectDepositsSection({
  deposits,
  allocations,
  netPay,
  onChange,
  hint,
  onReset,
}: {
  deposits: DirectDeposit[];
  allocations: ReturnType<typeof useSalaryData>["calculation"]["depositAllocations"];
  netPay: number;
  onChange: (list: DirectDeposit[]) => void;
  hint?: string;
  onReset?: () => void;
}) {
  const [sheetOpen, setSheetOpen] = useState(false);
  const [editingDeposit, setEditingDeposit] = useState<DirectDeposit | null>(
    null,
  );

  const allocationById = new Map(
    allocations.map((a) => [a.deposit.id, a.calculatedAmount]),
  );
  const allocatedSum = allocations.reduce((s, a) => s + a.calculatedAmount, 0);
  const unallocated = netPay - allocatedSum;

  const openAdd = () => {
    setEditingDeposit(null);
    setSheetOpen(true);
  };

  const openEdit = (deposit: DirectDeposit) => {
    setEditingDeposit(deposit);
    setSheetOpen(true);
  };

  const closeSheet = () => {
    setSheetOpen(false);
    setEditingDeposit(null);
  };

  const saveDeposit = (draft: DirectDeposit) => {
    const exists = deposits.some((d) => d.id === draft.id);
    let next = exists
      ? deposits.map((d) => (d.id === draft.id ? draft : d))
      : [...deposits, { ...draft, sortOrder: deposits.length }];

    if (draft.isRemainder) {
      next = next.map((d) => ({
        ...d,
        isRemainder: d.id === draft.id,
      }));
    }

    onChange(next);
    closeSheet();
  };

  const removeDeposit = (id: string) => {
    onChange(deposits.filter((d) => d.id !== id));
  };

  const sorted = [...deposits].sort((a, b) => a.sortOrder - b.sortOrder);

  return (
    <section className="card p-5 space-y-3">
      <div className="flex items-center justify-between gap-2">
        <h2 className="section-title">Direct Deposits</h2>
        <div className="flex items-center gap-2 shrink-0">
          {onReset ? (
            <button
              type="button"
              className="btn-ghost text-xs py-1"
              onClick={onReset}
            >
              Reset to Summary
            </button>
          ) : null}
          <button type="button" className="btn-ghost text-sm py-1" onClick={openAdd}>
            Add
          </button>
        </div>
      </div>
      {hint ? <p className="text-xs text-muted">{hint}</p> : null}
      {sorted.length === 0 ? (
        <p className="text-sm text-muted">
          Split take-home pay across accounts (percent, fixed amount, or
          remainder).
        </p>
      ) : (
        <ul className="space-y-2">
          {sorted.map((d) => {
            const amount = allocationById.get(d.id);
            return (
              <li
                key={d.id}
                className="flex items-center justify-between gap-3 py-2 divider-line last:border-0"
              >
                <div className="min-w-0 flex-1">
                  <p className="text-body font-medium truncate">
                    {d.accountName || "Untitled account"}
                  </p>
                  <p className="text-xs text-muted truncate">
                    {[d.bankName, depositSplitLabel(d)]
                      .filter(Boolean)
                      .join(" · ")}
                  </p>
                </div>
                <div className="flex items-center gap-2 shrink-0">
                  {amount != null ? (
                    <span className="money text-base">{formatUsd(amount)}</span>
                  ) : null}
                  <button
                    type="button"
                    className="btn-ghost text-xs py-1 px-2"
                    onClick={() => openEdit(d)}
                  >
                    Edit
                  </button>
                  <button
                    type="button"
                    className="btn-ghost text-xs py-1 px-2 text-error"
                    onClick={() => removeDeposit(d.id)}
                  >
                    Del
                  </button>
                </div>
              </li>
            );
          })}
          {unallocated > 0.01 ? (
            <li className="flex items-center justify-between gap-3 py-2 border-t border-border">
              <p className="text-sm font-medium text-warn">Unallocated</p>
              <span className="money text-warn">{formatUsd(unallocated)}</span>
            </li>
          ) : null}
        </ul>
      )}

      <DirectDepositSheet
        open={sheetOpen}
        deposit={editingDeposit}
        depositCount={deposits.length}
        onClose={closeSheet}
        onSave={saveDeposit}
      />
    </section>
  );
}

