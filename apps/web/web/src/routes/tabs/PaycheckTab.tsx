function decimalDisplayValue(n: number): string {
  return n === 0 ? "" : String(n);
}

function percentDisplayValue(rate: number | null | undefined): string {
  if (rate == null) return "";
  const pct = rate * 100;
  return pct === 0 ? "" : String(pct);
}

function PercentRateInput({
  value,
  onChange,
  defaultRate,
  disabled,
  className,
  "aria-label": ariaLabel,
}: {
  value: number | null | undefined;
  onChange: (rate: number | null) => void;
  defaultRate: number;
  disabled?: boolean;
  className?: string;
  "aria-label"?: string;
}) {
  const [text, setText] = useState(() => percentDisplayValue(value));

  useEffect(() => {
    setText((prev) => {
      const parsed = Number.parseFloat(prev);
      if (
        prev !== "" &&
        prev !== "." &&
        Number.isFinite(parsed) &&
        value != null &&
        Math.abs(parsed / 100 - value) < 1e-9
      ) {
        return prev;
      }
      if (prev === "" && (value == null || value === 0)) return prev;
      return percentDisplayValue(value);
    });
  }, [value]);

  return (
    <input
      className={className}
      inputMode="decimal"
      placeholder={`${(defaultRate * 100).toFixed(1)}%`}
      value={text}
      disabled={disabled}
      aria-label={ariaLabel}
      onChange={(e) => {
        const raw = e.target.value;
        if (raw !== "" && !/^\d*\.?\d*$/.test(raw)) return;
        setText(raw);
        if (raw === "" || raw === ".") {
          onChange(null);
          return;
        }
        const n = Number.parseFloat(raw);
        if (Number.isFinite(n)) onChange(n / 100);
      }}
      onBlur={() => {
        if (text === "" || text === ".") {
          setText("");
          onChange(null);
          return;
        }
        const n = Number.parseFloat(text);
        if (Number.isFinite(n)) {
          onChange(n / 100);
          setText(String(n));
        } else {
          setText("");
          onChange(null);
        }
      }}
    />
  );
}

function DecimalInput({
  value,
  onChange,
  className,
  placeholder,
}: {
  value: number;
  onChange: (n: number) => void;
  className?: string;
  placeholder?: string;
}) {
  const [text, setText] = useState(() => decimalDisplayValue(value));

  useEffect(() => {
    setText((prev) => {
      const parsed = Number.parseFloat(prev);
      if (prev !== "" && prev !== "." && Number.isFinite(parsed) && parsed === value) {
        return prev;
      }
      return decimalDisplayValue(value);
    });
  }, [value]);

  return (
    <input
      className={className}
      inputMode="decimal"
      placeholder={placeholder}
      value={text}
      onChange={(e) => {
        const raw = e.target.value;
        if (raw !== "" && !/^\d*\.?\d*$/.test(raw)) return;
        setText(raw);
        if (raw === "" || raw === ".") {
          onChange(0);
          return;
        }
        const n = Number.parseFloat(raw);
        if (Number.isFinite(n)) onChange(n);
      }}
      onBlur={() => {
        const n = Number.parseFloat(text);
        setText(Number.isFinite(n) ? String(n) : "");
        if (Number.isFinite(n)) onChange(n);
        else onChange(0);
      }}
    />
  );
}

