            totalPostTaxDeductions = calc.totalPostTaxDeductions,
            overtimeHours = overtimeHours,
            notes = notes,
            earnings = lines.earnings,
            taxes = lines.taxes,
            preTaxDeductions = lines.preTaxDeductions,
            postTaxDeductions = lines.postTaxDeductions,
            autoGenerated = autoGenerated
        )
    }

