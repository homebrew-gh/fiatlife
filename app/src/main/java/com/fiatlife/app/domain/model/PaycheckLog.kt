/**
 * Year-to-date earnings/tax/deduction aggregation. Mirrors the web `summarizeYtd`
 * so both platforms present the same itemized summary.
 */
object SalarySummary {

    fun newId(): String = UUID.randomUUID().toString()

    /** The pay rate in effect at [whenMs], resolved from base config + raise history. */
    fun effectiveRateAt(config: SalaryConfig, whenMs: Long): EffectiveRate {
        val base = EffectiveRate(
            payType = config.payType,
            hourlyRate = config.hourlyRate,
            annualSalary = config.annualSalary,
            standardHoursPerPeriod = config.standardHoursPerPeriod
        )
        val applicable = config.payRateHistory
            .filter { it.effectiveDate <= whenMs }
            .maxByOrNull { it.effectiveDate }
            ?: return base
        return EffectiveRate(
            payType = applicable.payType ?: base.payType,
            hourlyRate = applicable.hourlyRate ?: base.hourlyRate,
            annualSalary = applicable.annualSalary ?: base.annualSalary,
            standardHoursPerPeriod = applicable.standardHoursPerPeriod
                ?: base.standardHoursPerPeriod
        )
    }

    fun periodRegularGross(rate: EffectiveRate, frequency: PayFrequency): Double {
        return if (rate.payType == PayType.SALARY) {
            rate.annualSalary / frequency.periodsPerYear
        } else {
            rate.hourlyRate * rate.standardHoursPerPeriod
        }
    }

    fun monthBoundsFromAnchor(monthAnchorMillis: Long): Pair<Long, Long> {
        val start = Calendar.getInstance().apply {
            timeInMillis = monthAnchorMillis
            set(Calendar.DAY_OF_MONTH, 1)
            set(Calendar.HOUR_OF_DAY, 0)
            set(Calendar.MINUTE, 0)
            set(Calendar.SECOND, 0)
            set(Calendar.MILLISECOND, 0)
        }.timeInMillis
        val end = Calendar.getInstance().apply {
            timeInMillis = start
            add(Calendar.MONTH, 1)
            add(Calendar.MILLISECOND, -1)
        }.timeInMillis
        return start to end
    }

    fun scheduledPaydaysInMonth(
        config: SalaryConfig,
        monthAnchorMillis: Long
    ): List<Long> {
        val (start, end) = monthBoundsFromAnchor(monthAnchorMillis)
        val year = yearOf(monthAnchorMillis)
        val anchor = resolvePaydayAnchor(config, year, end)
            ?: config.firstPaydayOfYearMillis
            ?: if (config.payFrequency == PayFrequency.WEEKLY ||
                config.payFrequency == PayFrequency.BIWEEKLY
            ) {
                null
            } else {
                yearStart(year)
            }
            ?: return emptyList()
        return enumeratePaydays(anchor, config.payFrequency, start, end)
    }

    fun paycheckCountInMonth(
        config: SalaryConfig?,
        monthAnchorMillis: Long = System.currentTimeMillis()
    ): Int {
        if (config == null) return 0
        val scheduled = scheduledPaydaysInMonth(config, monthAnchorMillis)
        if (scheduled.isNotEmpty()) return scheduled.size
        return when (config.payFrequency) {
            PayFrequency.SEMIMONTHLY -> 2
            PayFrequency.MONTHLY -> 1
            else -> {
                val anchor = config.firstPaydayOfYearMillis ?: return 0
                val (start, end) = monthBoundsFromAnchor(monthAnchorMillis)
                countPaychecksInRange(anchor, config.payFrequency, start, end)
                    .coerceAtLeast(1)
            }
        }
    }

    fun computeMonthlyTakeHome(
        config: SalaryConfig,
        monthAnchorMillis: Long = System.currentTimeMillis(),
        asOf: Long = System.currentTimeMillis()
    ): MonthlyTakeHomeProjection {
        val (monthStart, monthEnd) = monthBoundsFromAnchor(monthAnchorMillis)
        val logs = config.paycheckLog
            .filter { it.payDate in monthStart..monthEnd }
            .sortedBy { it.payDate }

        val loggedTakeHome = logs.sumOf { it.netPay }
        val loggedGross = logs.sumOf { it.grossPay }
        val loggedTaxes = logs.sumOf { it.totalTaxes ?: 0.0 }
        val loggedPreTax = logs.sumOf { it.totalPreTaxDeductions ?: 0.0 }
        val loggedPostTax = logs.sumOf { it.totalPostTaxDeductions ?: 0.0 }
        val loggedDeductions = loggedPreTax + loggedPostTax
        val loggedOvertimeHours = logs.sumOf { entryOvertimeHours(it) }
        val loggedBonusTotal = logs.sumOf { entry ->
            entry.earnings
                .filter { it.label.trim().contains("bonus", ignoreCase = true) }
                .sumOf { it.amount }
        }
        val loggedDays = logs.map { startOfDay(it.payDate) }.toSet()

        val baseCalc = PaycheckCalculator.calculate(
            config.copy(overtimeHours = 0.0),
            asOf
        )
        val perPaycheckNet = baseCalc.netPay

        val scheduled = scheduledPaydaysInMonth(config, monthAnchorMillis)
        val scheduledCount = if (scheduled.isNotEmpty()) {
            scheduled.size
        } else {
            paycheckCountInMonth(config, monthAnchorMillis)
        }

        val remainingCount = if (scheduled.isNotEmpty()) {
            scheduled.count { startOfDay(it) !in loggedDays }
        } else {
            (scheduledCount - logs.size).coerceAtLeast(0)
        }

        val projectedRemainder = remainingCount * perPaycheckNet
        val projectedGross = remainingCount * baseCalc.grossPay
        val projectedTaxes = remainingCount * baseCalc.totalTaxes
        val projectedDeductions = remainingCount *
            (baseCalc.totalPreTaxDeductions + baseCalc.totalPostTaxDeductions)

        val source = when {
            logs.isNotEmpty() && remainingCount == 0 -> MonthlyTakeHomeSource.LOGGED
            logs.isNotEmpty() && remainingCount > 0 -> MonthlyTakeHomeSource.MIXED
            else -> MonthlyTakeHomeSource.ESTIMATED
        }

        return MonthlyTakeHomeProjection(
            totalTakeHome = loggedTakeHome + projectedRemainder,
            totalGross = loggedGross + projectedGross,
            totalTaxes = loggedTaxes + projectedTaxes,
            totalDeductions = loggedDeductions + projectedDeductions,
            loggedTakeHome = loggedTakeHome,
            loggedGross = loggedGross,
            loggedTaxes = loggedTaxes,
            loggedDeductions = loggedDeductions,
            projectedRemainder = projectedRemainder,
            projectedGross = projectedGross,
            projectedTaxes = projectedTaxes,
            projectedDeductions = projectedDeductions,
            perPaycheckNet = perPaycheckNet,
            loggedPaycheckCount = logs.size,
            remainingPaycheckCount = remainingCount,
            scheduledPaychecksInMonth = scheduledCount,
            loggedOvertimeHours = loggedOvertimeHours,
            loggedBonusTotal = loggedBonusTotal,
            source = source
        )
    }

    fun projectFederalTaxReturn(
        config: SalaryConfig,
        annual: AnnualExtrapolation
    ): FederalTaxReturnProjection {
        val annualGross = annual.annualGrossPay
        val annualPreTax = annual.annualPreTaxDeductions
        val adjustedGrossIncome = annualGross - annualPreTax
        val standardDeduction = FederalTaxTables.standardDeduction(config.filingStatus)
        val federalTaxableIncome = (adjustedGrossIncome - standardDeduction).coerceAtLeast(0.0)
        val overrides = config.taxOverrides

        val estimatedFederalTaxOwed = if (overrides.isExemptFromFederal) {
            0.0
        } else if (overrides.customFederalTaxRate != null) {
            adjustedGrossIncome * overrides.customFederalTaxRate!!
        } else {
            FederalTaxTables.calculateTax(federalTaxableIncome, config.filingStatus)
        }

        val federalWithheld = annual.taxes
            .filter { it.label.trim().matches(Regex("(?i)federal\\s+income\\s+tax")) }
            .sumOf { it.amount }

        return FederalTaxReturnProjection(
            annualGross = annualGross,
            annualPreTaxDeductions = annualPreTax,
            adjustedGrossIncome = adjustedGrossIncome,
            standardDeduction = standardDeduction,
            federalTaxableIncome = federalTaxableIncome,
            estimatedFederalTaxOwed = estimatedFederalTaxOwed,
            federalWithheld = federalWithheld,
            refundOrBalance = federalWithheld - estimatedFederalTaxOwed
        )
    }

    fun logsForYear(config: SalaryConfig, year: Int): List<PaycheckLogEntry> {
        return config.paycheckLog
            .filter { yearOf(it.payDate) == year }
            .sortedByDescending { it.payDate }
    }

    private const val DAY_MS = 24L * 60 * 60 * 1000

    private fun payPeriodStepMs(frequency: PayFrequency): Long? = when (frequency) {
        PayFrequency.WEEKLY -> 7L * DAY_MS
        PayFrequency.BIWEEKLY -> 14L * DAY_MS
        else -> null
    }

    /**
     * Best anchor for scheduled payday enumeration. For weekly/biweekly pay, prefers an
     * anchor that matches logged paycheck dates (including when first payday was set
     * after logging or set to a nearby but incorrect date).
     */
    fun resolvePaydayAnchor(
        config: SalaryConfig,
        year: Int,
        asOf: Long = System.currentTimeMillis()
    ): Long? {
        val freq = config.payFrequency
        if (freq != PayFrequency.WEEKLY && freq != PayFrequency.BIWEEKLY) {
            return config.firstPaydayOfYearMillis ?: yearStart(year)
        }

        val loggedDays = logsForYear(config, year)
            .map { startOfDay(it.payDate) }
            .filter { it <= startOfDay(asOf) }
        if (loggedDays.isEmpty()) {
            return config.firstPaydayOfYearMillis
        }

        val stepMs = payPeriodStepMs(freq)!!
        val rangeEnd = minOf(asOf, yearEnd(year))
        val rangeStart = yearStart(year)
        val configured = config.firstPaydayOfYearMillis?.let { startOfDay(it) }

        val candidates = linkedSetOf<Long>()
        configured?.let { candidates.add(it) }
        for (logged in loggedDays) {
            candidates.add(logged)
            for (k in 0 until 30) {
                candidates.add(logged - k * stepMs)
            }
        }

        var bestAnchor: Long? = null
        var bestScore = -1
        var bestPreferConfigured = false

        for (anchor in candidates) {
            val scheduled = enumeratePaydays(anchor, freq, rangeStart, rangeEnd).toSet()
            val matched = loggedDays.count { it in scheduled }
            val preferConfigured = configured != null && anchor == configured
            if (matched > bestScore || (matched == bestScore && preferConfigured && !bestPreferConfigured)) {
                bestScore = matched
                bestAnchor = anchor
                bestPreferConfigured = preferConfigured
            }
        }

        return bestAnchor
    }

    /** Whether scheduled paydays can be compared to the log for this pay frequency. */
    fun canDetectMissingPaychecks(config: SalaryConfig, year: Int? = null): Boolean =
        when (config.payFrequency) {
            PayFrequency.WEEKLY, PayFrequency.BIWEEKLY ->
                config.firstPaydayOfYearMillis != null ||
                    (year != null && logsForYear(config, year).isNotEmpty())
            else -> true
        }

    /** Scheduled paydays in [year] through [asOf] that have no matching log entry. */
    fun missingPaydaysForYear(
        config: SalaryConfig,
        year: Int,
        asOf: Long = System.currentTimeMillis()
    ): List<Long> {
        if (!canDetectMissingPaychecks(config, year)) return emptyList()
        val anchor = resolvePaydayAnchor(config, year, asOf) ?: return emptyList()
        val scheduled = enumeratePaydays(
            anchor,
            config.payFrequency,
            yearStart(year),
            minOf(asOf, yearEnd(year))
        )
        if (scheduled.isEmpty()) return emptyList()
        val loggedDays = logsForYear(config, year).map { startOfDay(it.payDate) }.toSet()
        return scheduled.filter { it !in loggedDays }
    }

    fun yearOf(ms: Long): Int {
        val cal = Calendar.getInstance().apply { timeInMillis = ms }
        return cal.get(Calendar.YEAR)
    }

    private fun yearStart(year: Int): Long =
        Calendar.getInstance().apply {
            clear(); set(year, Calendar.JANUARY, 1, 0, 0, 0)
        }.timeInMillis

    private fun yearEnd(year: Int): Long =
        Calendar.getInstance().apply {
            clear(); set(year, Calendar.DECEMBER, 31, 23, 59, 59)
        }.timeInMillis

    private fun startOfDay(ms: Long): Long =
        Calendar.getInstance().apply {
            timeInMillis = ms
            set(Calendar.HOUR_OF_DAY, 0); set(Calendar.MINUTE, 0)
            set(Calendar.SECOND, 0); set(Calendar.MILLISECOND, 0)
        }.timeInMillis

    fun countPaychecksInRange(
        firstPaydayMillis: Long,
        frequency: PayFrequency,
        rangeStart: Long,
        rangeEnd: Long
    ): Int = enumeratePaydays(firstPaydayMillis, frequency, rangeStart, rangeEnd).size

    fun enumeratePaydays(
        firstPaydayMillis: Long,
        frequency: PayFrequency,
        rangeStart: Long,
        rangeEnd: Long
    ): List<Long> {
        val days = mutableListOf<Long>()
        when (frequency) {
            PayFrequency.SEMIMONTHLY -> {
                val cursor = Calendar.getInstance().apply {
                    timeInMillis = rangeStart
                    set(Calendar.DAY_OF_MONTH, 1)
                }
                while (cursor.timeInMillis <= rangeEnd) {
                    val y = cursor.get(Calendar.YEAR)
                    val m = cursor.get(Calendar.MONTH)
                    val mid = Calendar.getInstance().apply {
                        clear(); set(y, m, 15)
                    }.timeInMillis
                    val monthEnd = Calendar.getInstance().apply {
                        clear(); set(y, m, 1); set(Calendar.DAY_OF_MONTH, getActualMaximum(Calendar.DAY_OF_MONTH))
                    }.timeInMillis
                    if (mid in rangeStart..rangeEnd) days.add(mid)
                    if (monthEnd in rangeStart..rangeEnd) days.add(monthEnd)
                    cursor.add(Calendar.MONTH, 1)
                }
            }
            PayFrequency.MONTHLY -> {
                val cursor = Calendar.getInstance().apply {
                    timeInMillis = rangeStart
                    set(Calendar.DAY_OF_MONTH, 1)
                }
                while (cursor.timeInMillis <= rangeEnd) {
                    val y = cursor.get(Calendar.YEAR)
                    val m = cursor.get(Calendar.MONTH)
                    val maxDay = cursor.getActualMaximum(Calendar.DAY_OF_MONTH)
                    val payday = Calendar.getInstance().apply {
                        clear(); set(y, m, minOf(maxDay, 15))
                    }.timeInMillis
                    if (payday in rangeStart..rangeEnd) days.add(payday)
                    cursor.add(Calendar.MONTH, 1)
                }
            }
            else -> {
                val stepMs = if (frequency == PayFrequency.WEEKLY)
                    7L * 24 * 60 * 60 * 1000 else 14L * 24 * 60 * 60 * 1000
                var payday = startOfDay(firstPaydayMillis)
                var i = 0
                while (i < 500 && payday <= rangeEnd) {
                    if (payday >= rangeStart) days.add(payday)
                    payday += stepMs
                    i++
                }
            }
        }
        return days.sorted()
    }

    fun scheduledPaychecksYtd(config: SalaryConfig, year: Int, asOf: Long = System.currentTimeMillis()): Int {
        val anchor = config.firstPaydayOfYearMillis
        val start = yearStart(year)
        val end = minOf(asOf, yearEnd(year))
        if (anchor == null) {
            val periods = config.payFrequency.periodsPerYear
            val elapsed = (end - start).toDouble() / (yearEnd(year) - start + 1)
            return (elapsed * periods).toInt().coerceAtLeast(1)
        }
        return countPaychecksInRange(anchor, config.payFrequency, start, end).coerceAtLeast(0)
    }

    fun scheduledPaychecksInYear(config: SalaryConfig, year: Int): Int {
        val anchor = config.firstPaydayOfYearMillis ?: return config.payFrequency.periodsPerYear
        return countPaychecksInRange(anchor, config.payFrequency, yearStart(year), yearEnd(year))
    }

    private fun mergeLines(groups: List<List<PaycheckLineItem>>): List<YtdBreakdownLine> {
        val map = LinkedHashMap<String, YtdBreakdownLine>()
        for (group in groups) {
            for (item in group) {
                val label = item.label.ifBlank { "Other" }
                val existing = map[label]
                if (existing != null) {
                    map[label] = existing.copy(
                        amount = existing.amount + item.amount,
                        hours = existing.hours + (item.hours ?: 0.0)
                    )
                } else {
                    map[label] = YtdBreakdownLine(label, item.amount, item.hours ?: 0.0)
                }
            }
        }
        return map.values.filter { it.amount != 0.0 || it.hours != 0.0 }
    }

    private fun entryOvertimeHours(e: PaycheckLogEntry): Double {
        e.overtimeHours?.let { return it }
        val ot = e.earnings.firstOrNull { Regex("overtime|^ot\\b", RegexOption.IGNORE_CASE).containsMatchIn(it.label) }
        return ot?.hours ?: 0.0
    }

    private fun entryEarnings(e: PaycheckLogEntry): List<PaycheckLineItem> =
        if (e.earnings.isNotEmpty()) e.earnings
        else listOf(PaycheckLineItem(e.id, "Earnings", e.grossPay))

    private fun entryTaxes(e: PaycheckLogEntry): List<PaycheckLineItem> =
        if (e.taxes.isNotEmpty()) e.taxes
        else e.totalTaxes?.let { listOf(PaycheckLineItem(e.id, "Taxes", it)) } ?: emptyList()

    private fun scaleBreakdownLines(
        lines: List<YtdBreakdownLine>,
        factor: Double
    ): List<YtdBreakdownLine> =
        lines.map { line ->
            line.copy(
                amount = line.amount * factor,
                hours = line.hours * factor
            )
        }

    private fun extrapolationFromModel(
        modelAnnual: AnnualProjection,
        scheduledInYear: Int
    ): AnnualExtrapolation {
        val perPaycheckGross =
            if (scheduledInYear > 0) modelAnnual.annualGrossPay / scheduledInYear else 0.0
        return AnnualExtrapolation(
            source = AnnualExtrapolation.Source.ESTIMATED,
            basedOnPaychecks = 0,
            scheduledPaychecksInYear = scheduledInYear,
            remainingPaychecksProjected = scheduledInYear,
            averageOvertimeHoursPerPaycheck = 0.0,
            projectOvertimeForward = true,
            annualGrossPay = modelAnnual.annualGrossPay,
            annualNetPay = modelAnnual.annualNetPay,
            annualTotalTaxes = modelAnnual.annualTotalTaxes,
            annualTotalDeductions =
                modelAnnual.annualPreTaxDeductions + modelAnnual.annualPostTaxDeductions,
            annualPreTaxDeductions = modelAnnual.annualPreTaxDeductions,
            annualPostTaxDeductions = modelAnnual.annualPostTaxDeductions,
            overtimeHours = modelAnnual.overtimeHoursUsed,
            perPaycheckNet = modelAnnual.perPaycheckNet,
            perPaycheckGross = perPaycheckGross,
            earnings = buildList {
                add(YtdBreakdownLine("Regular", modelAnnual.annualRegularPay))
                if (modelAnnual.annualOvertimePay > 0) {
                    add(
                        YtdBreakdownLine(
                            "Overtime",
                            modelAnnual.annualOvertimePay,
                            modelAnnual.overtimeHoursUsed
                        )
                    )
                }
            },
            taxes = buildList {
                add(YtdBreakdownLine("Federal income tax", modelAnnual.annualFederalTax))
                add(YtdBreakdownLine("State income tax", modelAnnual.annualStateTax))
                if (modelAnnual.annualCountyTax > 0) {
                    add(YtdBreakdownLine("County/local tax", modelAnnual.annualCountyTax))
                }
                add(YtdBreakdownLine("Social Security", modelAnnual.annualSocialSecurity))
                add(YtdBreakdownLine("Medicare", modelAnnual.annualMedicare))
            }.filter { it.amount != 0.0 },
            preTaxDeductions = modelAnnual.preTaxDeductionBreakdown.map {
                YtdBreakdownLine(it.name.ifBlank { "Pre-tax" }, it.amount)
            },
            postTaxDeductions = modelAnnual.postTaxDeductionBreakdown.map {
                YtdBreakdownLine(it.name.ifBlank { "Post-tax" }, it.amount)
            },
            employerContributions = emptyList(),
            effectiveTaxRate = modelAnnual.effectiveTaxRate
        )
    }

    private fun mergeBreakdownLineGroups(
        groups: List<List<YtdBreakdownLine>>
    ): List<YtdBreakdownLine> {
        val map = linkedMapOf<String, YtdBreakdownLine>()
        for (group in groups) {
            for (line in group) {
                val existing = map[line.label]
                if (existing != null) {
                    map[line.label] = existing.copy(
                        amount = existing.amount + line.amount,
                        hours = existing.hours + line.hours
                    )
                } else {
                    map[line.label] = line.copy()
                }
            }
        }
        return map.values.filter { it.amount != 0.0 || it.hours != 0.0 }
    }

    private fun scaleBreakdownForRemaining(
        lines: List<YtdBreakdownLine>,
        remaining: Int
    ): List<YtdBreakdownLine> =
        lines.map { line ->
            line.copy(
                amount = line.amount * remaining,
                hours = line.hours * remaining
            )
        }

    private data class ForwardBreakdown(
        val earnings: List<YtdBreakdownLine>,
        val taxes: List<YtdBreakdownLine>,
        val preTaxDeductions: List<YtdBreakdownLine>,
        val postTaxDeductions: List<YtdBreakdownLine>
    )

    private fun forwardBreakdownFromCalc(
        calc: PaycheckCalculation,
        overtimeHours: Double,
        config: SalaryConfig
    ): ForwardBreakdown {
        val earnings = buildList {
            add(YtdBreakdownLine("Regular", calc.regularPay))
            if (calc.overtimePay > 0) {
                add(YtdBreakdownLine("Overtime", calc.overtimePay, overtimeHours))
            }
        }
        val taxes = buildList {
            add(YtdBreakdownLine("Federal income tax", calc.federalTax))
            add(YtdBreakdownLine("State income tax", calc.stateTax))
            if (calc.countyTax > 0) {
                add(YtdBreakdownLine("County/local tax", calc.countyTax))
            }
            add(YtdBreakdownLine("Social Security", calc.socialSecurity))
            add(YtdBreakdownLine("Medicare", calc.medicare))
        }.filter { it.amount != 0.0 }
        return ForwardBreakdown(
            earnings = earnings,
            taxes = taxes,
            preTaxDeductions = calc.preTaxDeductionBreakdown.map {
                YtdBreakdownLine(it.name.ifBlank { "Pre-tax" }, it.amount)
            },
            postTaxDeductions = calc.postTaxDeductionBreakdown.map {
                YtdBreakdownLine(it.name.ifBlank { "Post-tax" }, it.amount)
            }
        )
    }

    /**
     * YTD actuals plus latest pay rate for remaining scheduled paychecks.
     * OT averages over logged paychecks and projects forward when enabled.
     */
    fun extrapolateAnnualFromLogs(
        config: SalaryConfig,
        calc: PaycheckCalculation,
        modelAnnual: AnnualProjection,
        year: Int,
        projectOvertimeForward: Boolean = true,
        asOf: Long = System.currentTimeMillis()
    ): AnnualExtrapolation {
        val scheduledInYear = scheduledPaychecksInYear(config, year)
        val scheduledYtd = scheduledPaychecksYtd(config, year, asOf)
        val remaining = (scheduledInYear - scheduledYtd).coerceAtLeast(0)
        val logs = logsForYear(config, year).sortedBy { it.payDate }
        if (logs.isEmpty()) {
            return extrapolationFromModel(modelAnnual, scheduledInYear)
        }

        val n = logs.size
        val latest = logs.last()
        val rate = effectiveRateAt(config, latest.payDate)
        val ytdGross = logs.sumOf { it.grossPay }
        val ytdNet = logs.sumOf { it.netPay }
        val ytdTaxes = logs.sumOf { it.totalTaxes ?: 0.0 }
        val ytdPreTax = logs.sumOf { it.totalPreTaxDeductions ?: 0.0 }
        val ytdPostTax = logs.sumOf { it.totalPostTaxDeductions ?: 0.0 }
        val ytdOTHours = logs.sumOf { entryOvertimeHours(it) }
        val avgOTPerPaycheck = if (n > 0) ytdOTHours / n else 0.0
        val forwardOT = if (projectOvertimeForward) avgOTPerPaycheck else 0.0

        val forwardConfig = config.copy(
            payType = rate.payType,
            hourlyRate = rate.hourlyRate,
            annualSalary = rate.annualSalary,
            standardHoursPerPeriod = rate.standardHoursPerPeriod,
            overtimeHours = forwardOT
        )
        val forwardPerPaycheck = PaycheckCalculator.calculate(forwardConfig)
        val forwardBreakdown = forwardBreakdownFromCalc(forwardPerPaycheck, forwardOT, config)

        val ytdEarnings = mergeLines(logs.map { entryEarnings(it) })
        val ytdTaxesLines = mergeLines(logs.map { entryTaxes(it) })
        val ytdPreTaxDeductions = mergeLines(logs.map { it.preTaxDeductions })
        val ytdPostTaxDeductions = mergeLines(logs.map { it.postTaxDeductions })
        val ytdEmployerContributions = mergeLines(logs.map { it.employerContributions })

        val annualGrossPay = ytdGross + forwardPerPaycheck.grossPay * remaining
        val annualNetPay = ytdNet + forwardPerPaycheck.netPay * remaining
        val annualTotalTaxes = ytdTaxes + forwardPerPaycheck.totalTaxes * remaining
        val annualPreTaxDeductions =
            ytdPreTax + forwardPerPaycheck.totalPreTaxDeductions * remaining
        val annualPostTaxDeductions =
            ytdPostTax + forwardPerPaycheck.totalPostTaxDeductions * remaining
        val annualOTHours = ytdOTHours + forwardOT * remaining

        return AnnualExtrapolation(
            source = AnnualExtrapolation.Source.LOGGED,
            basedOnPaychecks = n,
            scheduledPaychecksInYear = scheduledInYear,
            remainingPaychecksProjected = remaining,
            averageOvertimeHoursPerPaycheck = avgOTPerPaycheck,
            projectOvertimeForward = projectOvertimeForward,
            annualGrossPay = annualGrossPay,
            annualNetPay = annualNetPay,
            annualTotalTaxes = annualTotalTaxes,
            annualTotalDeductions = annualPreTaxDeductions + annualPostTaxDeductions,
            annualPreTaxDeductions = annualPreTaxDeductions,
            annualPostTaxDeductions = annualPostTaxDeductions,
            overtimeHours = annualOTHours,
            perPaycheckNet = if (scheduledInYear > 0) annualNetPay / scheduledInYear else 0.0,
            perPaycheckGross = if (scheduledInYear > 0) annualGrossPay / scheduledInYear else 0.0,
            earnings = mergeBreakdownLineGroups(
                listOf(ytdEarnings, scaleBreakdownForRemaining(forwardBreakdown.earnings, remaining))
            ),
            taxes = mergeBreakdownLineGroups(
                listOf(ytdTaxesLines, scaleBreakdownForRemaining(forwardBreakdown.taxes, remaining))
            ),
            preTaxDeductions = mergeBreakdownLineGroups(
                listOf(
                    ytdPreTaxDeductions,
                    scaleBreakdownForRemaining(forwardBreakdown.preTaxDeductions, remaining)
                )
            ),
            postTaxDeductions = mergeBreakdownLineGroups(
                listOf(
                    ytdPostTaxDeductions,
                    scaleBreakdownForRemaining(forwardBreakdown.postTaxDeductions, remaining)
                )
            ),
            employerContributions = ytdEmployerContributions,
            effectiveTaxRate =
                if (annualGrossPay > 0) annualTotalTaxes / annualGrossPay else calc.effectiveTaxRate
        )
    }

    fun summarize(
        config: SalaryConfig,
        calc: PaycheckCalculation,
        annual: AnnualProjection,
        year: Int,
        asOf: Long = System.currentTimeMillis(),
        projectOvertimeForward: Boolean = true
    ): YtdSummary {
        val logs = logsForYear(config, year)
        val scheduledYtd = scheduledPaychecksYtd(config, year, asOf)
        val scheduledInYear = scheduledPaychecksInYear(config, year)
        val remaining = (scheduledInYear - scheduledYtd).coerceAtLeast(0)
        val annualExtrapolation = extrapolateAnnualFromLogs(
            config,
            calc,
            annual,
            year,
            projectOvertimeForward,
            asOf
        )
        val perPaycheckNet = annualExtrapolation.perPaycheckNet

        if (logs.isNotEmpty()) {
            val grossPay = logs.sumOf { it.grossPay }
            val netPay = logs.sumOf { it.netPay }
            val totalTaxes = logs.sumOf { it.totalTaxes ?: 0.0 }
            val totalPre = logs.sumOf { it.totalPreTaxDeductions ?: 0.0 }
            val totalPost = logs.sumOf { it.totalPostTaxDeductions ?: 0.0 }
            val overtimeHours = logs.sumOf { entryOvertimeHours(it) }
            val expectedNet = perPaycheckNet * logs.size
            val annualNetTarget = annualExtrapolation.annualNetPay
            return YtdSummary(
                year = year,
                source = YtdSummary.Source.LOGGED,
                paycheckCount = logs.size,
                scheduledPaychecksYtd = scheduledYtd,
                scheduledPaychecksInYear = scheduledInYear,
                grossPay = grossPay,
                netPay = netPay,
                totalTaxes = totalTaxes,
                totalPreTaxDeductions = totalPre,
                totalPostTaxDeductions = totalPost,
                overtimeHours = overtimeHours,
                earnings = mergeLines(logs.map { entryEarnings(it) }),
                taxes = mergeLines(logs.map { entryTaxes(it) }),
                preTaxDeductions = mergeLines(logs.map { it.preTaxDeductions }),
                postTaxDeductions = mergeLines(logs.map { it.postTaxDeductions }),
                employerContributions = mergeLines(logs.map { it.employerContributions }),
                annualExtrapolation = annualExtrapolation,
                annualNetTarget = annualNetTarget,
                progressPercent = if (annualNetTarget > 0) netPay / annualNetTarget * 100 else 0.0,
                remainingPaychecks = remaining,
                expectedNetToDate = expectedNet,
                netVariance = netPay - expectedNet,
                projectedAnnualTaxes = annualExtrapolation.annualTotalTaxes
            )
        }

        val n = scheduledYtd
        val earnings = buildList {
            add(YtdBreakdownLine("Regular", calc.regularPay * n))
            if (calc.overtimePay > 0) {
                add(YtdBreakdownLine("Overtime", calc.overtimePay * n, config.overtimeHours * n))
            }
        }
        val taxes = buildList {
            add(YtdBreakdownLine("Federal income tax", calc.federalTax * n))
            add(YtdBreakdownLine("State income tax", calc.stateTax * n))
            if (calc.countyTax > 0) {
                add(YtdBreakdownLine(if (config.county.isNotBlank()) "${config.county} tax" else "Local tax", calc.countyTax * n))
            }
            add(YtdBreakdownLine("Social Security", calc.socialSecurity * n))
            add(YtdBreakdownLine("Medicare", calc.medicare * n))
        }.filter { it.amount != 0.0 }
        return YtdSummary(
            year = year,
            source = YtdSummary.Source.ESTIMATED,
            paycheckCount = n,
            scheduledPaychecksYtd = scheduledYtd,
            scheduledPaychecksInYear = scheduledInYear,
            grossPay = calc.grossPay * n,
            netPay = calc.netPay * n,
            totalTaxes = calc.totalTaxes * n,
            totalPreTaxDeductions = calc.totalPreTaxDeductions * n,
            totalPostTaxDeductions = calc.totalPostTaxDeductions * n,
            overtimeHours = config.overtimeHours * n,
            earnings = earnings,
            taxes = taxes,
            preTaxDeductions = calc.preTaxDeductionBreakdown.map { YtdBreakdownLine(it.name.ifBlank { "Pre-tax" }, it.amount * n) },
            postTaxDeductions = calc.postTaxDeductionBreakdown.map { YtdBreakdownLine(it.name.ifBlank { "Post-tax" }, it.amount * n) },
            employerContributions = emptyList(),
            annualExtrapolation = annualExtrapolation,
            annualNetTarget = annualExtrapolation.annualNetPay,
            progressPercent = if (annualExtrapolation.annualNetPay > 0) {
                calc.netPay * n / annualExtrapolation.annualNetPay * 100
            } else 0.0,
            remainingPaychecks = remaining,
            expectedNetToDate = perPaycheckNet * n,
            netVariance = 0.0,
            projectedAnnualTaxes = annualExtrapolation.annualTotalTaxes
        )
    }

