    const val INFERRED_RAISE_ID_PREFIX = "inferred-"

    data class InferredStartingPay(
        val effectiveDate: Long,
        val regularGrossPerPaycheck: Double,
        val payType: PayType,
        val hourlyRate: Double,
        val annualSalary: Double,
        val standardHoursPerPeriod: Double
    )

    data class InferredPayRateRaise(
        val change: PayRateChange,
        val percentIncrease: Double,
        val perPaycheckIncrease: Double,
        val previousRegularGross: Double,
        val newRegularGross: Double
    )

    data class InferredPayRates(
        val startingRate: InferredStartingPay?,
        val raises: List<InferredPayRateRaise>
    )

    private data class ParsedRegularPay(
        val regularGross: Double,
        val standardHours: Double
    )

    private fun regularGrossFromLog(
        entry: PaycheckLogEntry,
        config: SalaryConfig
    ): ParsedRegularPay? {
        if (entry.grossPay <= 0.0) return null

        var regularGross = entry.grossPay
        var standardHours = config.standardHoursPerPeriod

        if (entry.earnings.isNotEmpty()) {
            val regular = entry.earnings.find { it.label.trim().matches(Regex("(?i)^regular.*")) }
            val overtime = entry.earnings.find {
                it.label.trim().matches(Regex("(?i)(overtime|^ot\\b).*"))
            }
            if (regular != null) {
                regularGross = regular.amount
                if ((regular.hours ?: 0.0) > 0.0) standardHours = regular.hours!!
            } else if (overtime != null) {
                regularGross = (entry.grossPay - overtime.amount).coerceAtLeast(0.0)
            }
        } else if ((entry.overtimeHours ?: 0.0) > 0.0) {
            val rate = effectiveRateAt(config, entry.payDate)
            val overtimePay = rate.hourlyRate * config.overtimeMultiplier * entry.overtimeHours!!
            regularGross = (entry.grossPay - overtimePay).coerceAtLeast(0.0)
        }

        if (regularGross <= 0.0) return null
        return ParsedRegularPay(regularGross, standardHours)
    }

    private fun impliedRateFromRegularGross(
        regularGross: Double,
        payType: PayType,
        frequency: PayFrequency,
        standardHours: Double
    ): Pair<Double, Double> {
        return if (payType == PayType.SALARY) {
            0.0 to regularGross * frequency.periodsPerYear
        } else {
            (if (standardHours > 0.0) regularGross / standardHours else 0.0) to 0.0
        }
    }

    fun inferPayRatesFromLogs(config: SalaryConfig, year: Int): InferredPayRates {
        val logs = logsForYear(config, year).sortedBy { it.payDate }
        if (logs.isEmpty()) return InferredPayRates(null, emptyList())

        var previousRegular: Double? = null
        var startingRate: InferredStartingPay? = null
        val raises = mutableListOf<InferredPayRateRaise>()

        for (log in logs) {
            val parsed = regularGrossFromLog(log, config) ?: continue
            val (hourlyRate, annualSalary) = impliedRateFromRegularGross(
                parsed.regularGross,
                config.payType,
                config.payFrequency,
                parsed.standardHours
            )

            if (previousRegular == null) {
                startingRate = InferredStartingPay(
                    effectiveDate = log.payDate,
                    regularGrossPerPaycheck = parsed.regularGross,
                    payType = config.payType,
                    hourlyRate = hourlyRate,
                    annualSalary = annualSalary,
                    standardHoursPerPeriod = parsed.standardHours
                )
                previousRegular = parsed.regularGross
                continue
            }

            if (parsed.regularGross > previousRegular + 0.01) {
                val perPaycheckIncrease = parsed.regularGross - previousRegular
                val percentIncrease =
                    if (previousRegular > 0.0) perPaycheckIncrease / previousRegular * 100.0 else 0.0
                val change = PayRateChange(
                    id = "$INFERRED_RAISE_ID_PREFIX${log.payDate}",
                    effectiveDate = log.payDate,
                    payType = config.payType,
                    hourlyRate = hourlyRate,
                    annualSalary = annualSalary,
                    standardHoursPerPeriod = parsed.standardHours,
                    note = "+${"%.1f".format(percentIncrease)}% (+${
                        "%.2f".format(perPaycheckIncrease)
                    }/paycheck)"
                )
                raises.add(
                    InferredPayRateRaise(
                        change = change,
                        percentIncrease = percentIncrease,
                        perPaycheckIncrease = perPaycheckIncrease,
                        previousRegularGross = previousRegular,
                        newRegularGross = parsed.regularGross
                    )
                )
                previousRegular = parsed.regularGross
            }
        }

        return InferredPayRates(startingRate, raises)
    }

    fun applyInferredPayRatesToConfig(config: SalaryConfig, year: Int): SalaryConfig {
        val yearLogs = logsForYear(config, year)
        val manualRaises = config.payRateHistory.filter {
            !it.id.startsWith(INFERRED_RAISE_ID_PREFIX)
        }
        val otherInferred = config.payRateHistory.filter {
            it.id.startsWith(INFERRED_RAISE_ID_PREFIX) && yearOf(it.effectiveDate) != year
        }

        if (yearLogs.isEmpty()) {
            val cleaned = manualRaises + otherInferred
            return if (cleaned.size == config.payRateHistory.size) config
            else config.copy(payRateHistory = cleaned)
        }

        val inferred = inferPayRatesFromLogs(config, year)
        var next = config.copy(
            payRateHistory = manualRaises + otherInferred + inferred.raises.map { it.change }
        )
        inferred.startingRate?.let { start ->
            next = next.copy(
                payType = start.payType,
                hourlyRate = start.hourlyRate,
                annualSalary = start.annualSalary,
                standardHoursPerPeriod = start.standardHoursPerPeriod
            )
        }
        return next
    }

    fun applyInferredPayRatesForAllLogYears(config: SalaryConfig): SalaryConfig {
        val logYears = config.paycheckLog.map { yearOf(it.payDate) }.distinct()
        val inferredYears = config.payRateHistory
            .filter { it.id.startsWith(INFERRED_RAISE_ID_PREFIX) }
            .map { yearOf(it.effectiveDate) }
        var next = config
        for (year in (logYears + inferredYears).distinct()) {
            next = applyInferredPayRatesToConfig(next, year)
        }
        return next
    }
